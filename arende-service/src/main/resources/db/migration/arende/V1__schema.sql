-- Ärendetjänstens schema. Ändra aldrig en körd migration – lägg till en ny.

CREATE TABLE arende (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    typ                       VARCHAR(30)    NOT NULL,
    status                    VARCHAR(30)    NOT NULL,
    maltyp                    VARCHAR(10)    NOT NULL,
    -- Gäldenären finns i en annan tjänst och en annan databas. Därför ingen foreign key,
    -- bara id:t. Ärendetjänsten frågar gäldenärstjänsten via REST om gäldenären finns.
    galdenar_id               BIGINT         NOT NULL,
    borgenar                  VARCHAR(200)   NOT NULL,
    kapitalbelopp             NUMERIC(12, 2) NOT NULL,
    forfallodag               DATE           NOT NULL,
    konsumentfordran          BOOLEAN        NOT NULL DEFAULT FALSE,
    handlaggare               VARCHAR(100)   NOT NULL,
    registrerad               DATE           NOT NULL,
    delgivningsdatum          DATE,
    loneutmatning_per_manad   NUMERIC(12, 2),
    skuldsanering_beviljad    DATE,
    ursprungsarende_id        BIGINT REFERENCES arende (id),
    version                   BIGINT         NOT NULL DEFAULT 0
);

CREATE INDEX idx_arende_galdenar ON arende (galdenar_id);
CREATE INDEX idx_arende_status ON arende (status);

CREATE TABLE arende_inbetalning (
    arende_id  BIGINT         NOT NULL REFERENCES arende (id),
    rad        INT            NOT NULL,
    belopp     NUMERIC(12, 2) NOT NULL,
    datum      DATE           NOT NULL,
    PRIMARY KEY (arende_id, rad)
);

CREATE TABLE arende_dagbok (
    arende_id  BIGINT       NOT NULL REFERENCES arende (id),
    rad        INT          NOT NULL,
    datum      DATE         NOT NULL,
    handelse   VARCHAR(500) NOT NULL,
    PRIMARY KEY (arende_id, rad)
);
