CREATE TABLE galdenar (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    personnummer             VARCHAR(12)    NOT NULL,
    fornamn                  VARCHAR(100)   NOT NULL,
    efternamn                VARCHAR(100)   NOT NULL,
    adress                   VARCHAR(200)   NOT NULL,
    nettoinkomst_per_manad   NUMERIC(12, 2) NOT NULL DEFAULT 0,
    boendekostnad_per_manad  NUMERIC(12, 2) NOT NULL DEFAULT 0,
    sammanlevande            BOOLEAN        NOT NULL DEFAULT FALSE,
    version                  BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uk_galdenar_personnummer UNIQUE (personnummer)
);

CREATE TABLE galdenar_barn (
    galdenar_id  BIGINT NOT NULL REFERENCES galdenar (id),
    rad          INT    NOT NULL,
    fodelsear    INT    NOT NULL,
    PRIMARY KEY (galdenar_id, rad)
);
